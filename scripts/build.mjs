/**
 * Build both halves.
 *
 * The host bundle is one ESM file whose imports of the Harness runtime and zod
 * stay external (the profile resolves them from the installation). The browser
 * bundle keeps the platform modules external and is wrapped in DSH's lazy-CJS
 * loader envelope.
 *
 * Both writes target the existing paths with `writeFile`, which truncates in
 * place and preserves the profile's pnpm hardlink for hot reload.
 */
import { mkdir, writeFile } from 'node:fs/promises'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

import { build } from 'esbuild'

const sourceDirectory = dirname(fileURLToPath(import.meta.url))
const packageRoot = resolve(sourceDirectory, '..')

async function buildHost() {
  const result = await build({
    entryPoints: [resolve(packageRoot, 'src/host/index.js')],
    bundle: true,
    format: 'esm',
    platform: 'node',
    target: ['node22'],
    external: [
      '@deepseek-ai/cordis',
      '@deepseek-ai/dsh-storage-domain',
      '@deepseek-ai/dsh-tools',
      'zod',
    ],
    legalComments: 'none',
    sourcemap: false,
    write: false,
  })
  const code = result.outputFiles?.[0]?.text
  if (!code) throw new Error('esbuild produced no host bundle')
  const outputPath = resolve(packageRoot, 'lib/index.js')
  await mkdir(dirname(outputPath), { recursive: true })
  await writeFile(outputPath, `${code}\n`, 'utf8')
  console.log(`Wrote ${outputPath}`)
}

async function buildClient() {
  const result = await build({
    entryPoints: [resolve(packageRoot, 'src/client/index.jsx')],
    bundle: true,
    format: 'cjs',
    platform: 'browser',
    target: ['chrome100'],
    jsx: 'automatic',
    external: [
      'react',
      'react/jsx-runtime',
      'react-dom',
      '@deepseek-ai/dsh-client-ui-primitives',
    ],
    legalComments: 'none',
    sourcemap: false,
    write: false,
  })
  const bundled = result.outputFiles?.[0]?.text
  if (!bundled) throw new Error('esbuild produced no client bundle')
  const wrapped = `/* dsh-plugin-todos client bundle — generated by scripts/build.mjs */
window.__ModuleLoader__.load({
  id: "dsh-plugin-todos",
  factory: (require) => {
    var module = { exports: {} };
    var exports = module.exports;
${bundled}
    return module.exports;
  }
});
`
  const outputPath = resolve(packageRoot, 'lib/client.js')
  await mkdir(dirname(outputPath), { recursive: true })
  await writeFile(outputPath, wrapped, 'utf8')
  console.log(`Wrote ${outputPath}`)
}

await buildHost()
await buildClient()
